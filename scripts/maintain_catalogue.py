#!/usr/bin/env python3
"""Generate browse views and check local editorial integrity. No external URLs are fetched."""
import argparse
import collections
import os
import re
from pathlib import Path
import yaml

ROOT = Path(__file__).resolve().parents[1]

class UniqueLoader(yaml.SafeLoader):
    pass

def mapping(loader, node, deep=False):
    result = {}
    for key_node, value_node in node.value:
        key = loader.construct_object(key_node, deep=deep)
        if key in result:
            raise ValueError(f'Duplicate YAML key: {key}')
        result[key] = loader.construct_object(value_node, deep=deep)
    return result

UniqueLoader.add_constructor(yaml.resolver.BaseResolver.DEFAULT_MAPPING_TAG, mapping)

def load(path):
    return yaml.load((ROOT / path).read_text(), Loader=UniqueLoader)

def frontmatter(path):
    text = path.read_text()
    if not text.startswith('---\n'):
        raise ValueError(f'Missing record metadata: {path.relative_to(ROOT)}')
    metadata = yaml.load(text.split('---', 2)[1], Loader=UniqueLoader)
    title = re.search(r'^# (.+)$', text, re.M).group(1)
    return metadata, title

def relative(src, dst):
    return os.path.relpath(dst, str(Path(src).parent)).replace(os.sep, '/')

def generated(text):
    return '<!-- Generated by scripts/maintain_catalogue.py; edit canonical metadata instead. -->\n\n' + text.strip() + '\n'

def views(entries, industries):
    outputs = {}
    groups = collections.defaultdict(list)
    for e in entries:
        groups[e['model_category']].append(e)
    lines = ['# Catalogue', '', f'{len(entries)} discovery records. Editorial and source-check status are separate. All outcome claims require linked implementation evidence.', '', '[By industry](../industries/README.md) · [By ownership](by-ownership.md) · [Asset types](../guides/classification.md) · [Uncatalogued leads](discovery-backlog.md) · [Canonical metadata](index.yaml)', '', 'Source-specific narrative and references live in one record per stable ID. Metadata belongs in index.yaml. Browse tables are generated and must not be edited independently.']
    for kind, records in sorted(groups.items()):
        lines += ['', '## ' + kind.replace('-', ' ').capitalize(), '', '| Entry | Source check | Editorial status |', '|---|---|---|']
        for e in sorted(records, key=lambda x:x['title'].lower()):
            lines.append(f"| [{e['title']}]({e['profile']}) | {e['verification_status']} | {e['editorial_status']} |")
    outputs['catalogue/README.md'] = generated('\n'.join(lines))
    lines=['# Catalogue by Ownership', '', 'Ownership is not a quality rating or a regulatory classification. Asset-specific rights and evidence remain in the canonical records.', '', '[Full catalogue](README.md) · [Classification](../guides/classification.md)']
    owners=collections.defaultdict(list)
    for e in entries: owners[e['ownership_type']].append(e)
    for owner, records in sorted(owners.items()):
        lines+=['','## '+owner.replace('-',' ').capitalize(),'']
        lines += [f"- [{e['title']}]({e['profile']})" for e in sorted(records,key=lambda x:x['title'].lower())]
    outputs['catalogue/by-ownership.md']=generated('\n'.join(lines))
    lines=['# Industries','','Industry pages provide business context and links. Descriptions and licence assessments belong in canonical catalogue records.','','| Industry | Linked catalogue entries | Implementation cases |','|---|---:|---:|']
    for i in industries:
        lines.append(f"| [{i['title']}]({i['guide']}) | {len(i['catalogue_ids'])} | {len(i['implementation_cases'])} |")
        guide_path='industries/'+i['guide']
        guide=(ROOT/guide_path).read_text()
        table=['<!-- catalogue:start -->','| Entry | Category |','|---|---|']
        lookup={e['id']:e for e in entries}
        for identifier in i['catalogue_ids']:
            e=lookup[identifier]
            table.append(f"| [{e['title']}](../catalogue/{e['profile']}) | {e['model_category']} |")
        table.append('<!-- catalogue:end -->')
        outputs[guide_path]=re.sub(r'<!-- catalogue:start -->[\s\S]*?<!-- catalogue:end -->','\n'.join(table),guide)
    lines += ['', 'A zero case count indicates a coverage gap. Cross-industry entries are available through the [catalogue](../catalogue/README.md).']
    outputs['industries/README.md']=generated('\n'.join(lines))
    counts={}
    for kind in ('implementations','exceptions'):
        column='Provisional outcome and scope' if kind=='implementations' else 'Finding type'
        lines=[f'# {"Implementation Cases" if kind=="implementations" else "Exceptions and Limitations"}', '', 'These are source-based drafts. A reported outcome is not independent reproduction; an official capability limit is not automatically a customer failure.', '', f'| Record | {column} | Editorial status |', '|---|---|---|']
        records=sorted((ROOT/'evidence'/kind).glob('*.md'))
        records=[p for p in records if p.name!='README.md']
        counts[kind]=len(records)
        for p in records:
            m,title=frontmatter(p)
            result=(m['provisional_outcome']+': '+m['outcome_scope']) if kind=='implementations' else m['finding_type']
            lines.append(f"| [{title}]({p.name}) | {result} | {m['editorial_status']} |")
        lines += ['', '[Evidence policy](../../guides/evidence-policy.md) · [All evidence](../README.md)']
        outputs[f'evidence/{kind}/README.md']=generated('\n'.join(lines))
    unchecked=[e for e in entries if e['verification_status']=='not-reviewed']
    lines=['# Current Verification Status','','This page is generated from catalogue metadata. It reports source-check coverage, not independent verification of product performance or comprehensive rights clearance.','','| Measure | Count |','|---|---:|',f'| Catalogue records | {len(entries)} |',f'| Source check not completed | {len(unchecked)} |',f'| Partial source checks recorded | {len(entries)-len(unchecked)} |',f'| Implementation-case drafts | {counts["implementations"]} |',f'| Exception/boundary drafts | {counts["exceptions"]} |','','## Records still awaiting source checks','']
    lines += [f"- [{e['title']}](../catalogue/{e['profile']})" for e in unchecked]
    lines += ['','## Review boundaries','All current catalogue records remain drafts. Source dates identify the checks documented in individual records; they do not establish independent verification or comprehensive coverage. Licence scope, versions, deployment details and outcomes remain subject to each record\'s stated limitations.','','The flowsheet case is abstract-level; the IFC rights check includes development-versus-release limits; SAP retrieval was partial. See those records before using a conclusion. Historical batch notes are in the [archive](../archive/editorial-batch-log.md).']
    outputs['guides/verification-status.md']=generated('\n'.join(lines))
    return outputs

def check(entries, industries, expected):
    errors=[]
    ids=[e['id'] for e in entries]
    if len(ids)!=len(set(ids)): errors.append('Duplicate catalogue IDs')
    profile_paths=set()
    required=('id','title','profile','model_category','ownership_type','regulatory_status','editorial_status','verification_status','license_status','implementation_outcome')
    for e in entries:
        for key in required:
            if not e.get(key): errors.append(f"{e.get('id')}: missing {key}")
        p=ROOT/'catalogue'/e['profile']
        if e['profile']!='records/'+e['id']+'.md': errors.append(f"Non-canonical profile path: {e['id']}")
        if p in profile_paths: errors.append(f'Duplicate profile: {p}')
        profile_paths.add(p)
        if not p.is_file(): errors.append(f'Missing profile: {p}')
        for field,kind in [('implementation_cases','implementations'),('exception_records','exceptions')]:
            for link in e[field]:
                target=(ROOT/'catalogue'/link).resolve()
                if not target.is_file(): errors.append(f"{e['id']}: missing {field} {link}"); continue
                metadata,_=frontmatter(target)
                if e['id'] not in metadata['catalogue_ids']: errors.append(f"Non-reciprocal evidence link: {e['id']} -> {link}")
    actual=set((ROOT/'catalogue/records').glob('*.md'))
    if actual!=profile_paths: errors.append('Catalogue/profile inventory mismatch')
    evidence_ids=[]
    for kind in ('implementations','exceptions'):
        for p in (ROOT/'evidence'/kind).glob('*.md'):
            if p.name=='README.md': continue
            metadata,_=frontmatter(p)
            evidence_ids.append(metadata['id'])
            if kind=='implementations' and metadata.get('provisional_outcome') not in ('successful-within-scope','partially-successful','unsuccessful-for-use-case','inconclusive','not-evaluated'):
                errors.append(f'Invalid provisional outcome in {p.name}')
            for identifier in metadata['catalogue_ids']:
                if identifier not in ids: errors.append(f'Unknown catalogue ID {identifier} in {p.name}')
                else:
                    entry=next(e for e in entries if e['id']==identifier)
                    field='implementation_cases' if kind=='implementations' else 'exception_records'
                    backref=relative('catalogue/index.yaml',str(p.relative_to(ROOT)))
                    if backref not in entry[field]:errors.append(f'Missing catalogue backlink: {identifier} -> {p.name}')
    if len(evidence_ids)!=len(set(evidence_ids)): errors.append('Duplicate evidence IDs')
    for i in industries:
        if not (ROOT/'industries'/i['guide']).is_file():errors.append(f"Missing industry guide {i['guide']}")
        if len(i['catalogue_ids'])!=len(set(i['catalogue_ids'])):errors.append(f"Duplicate industry references: {i['id']}")
        for identifier in i['catalogue_ids']:
            if identifier not in ids: errors.append(f"Unknown industry catalogue ID: {identifier}")
            else:
                entry=next(e for e in entries if e['id']==identifier)
                if i['id'] not in entry['industries']:errors.append(f"Non-reciprocal industry membership: {identifier}")
    for e in entries:
        for industry in e['industries']:
            if industry=='cross-industry':continue
            group=next((i for i in industries if i['id']==industry),None)
            if group is None or e['id'] not in group['catalogue_ids']:errors.append(f"Missing industry backlink: {e['id']} -> {industry}")
    for p in ROOT.rglob('*.yaml'):
        yaml.load(p.read_text(),Loader=UniqueLoader)
    # Includes archived Markdown so path moves do not break retained historical sources.
    for p in ROOT.rglob('*.md'):
        text=p.read_text()
        for target in re.findall(r'\]\(([^\s)]+)\)',text):
            if re.match(r'^[a-zA-Z][\w+.-]*:',target) or target.startswith('#'):continue
            path=target.split('#',1)[0]
            if not (p.parent/path).exists():errors.append(f'Broken link: {p.relative_to(ROOT)} -> {target}')
    for p,text in expected.items():
        if not (ROOT/p).is_file() or (ROOT/p).read_text()!=text:errors.append(f'Stale generated view: {p}')
    if errors:
        raise SystemExit('\n'.join(errors))
    print(f'PASS: {len(entries)} unique catalogue records; {len(industries)} industry guides; {len(evidence_ids)} evidence records; links and generated views consistent.')

def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--write',action='store_true',help='Regenerate browse pages before checking')
    args=parser.parse_args()
    entries=load('catalogue/index.yaml')['entries']
    industries=load('industries/index.yaml')['industries']
    expected=views(entries,industries)
    if args.write:
        for p,text in expected.items():
            target=ROOT/p;target.parent.mkdir(parents=True,exist_ok=True);target.write_text(text)
    check(entries,industries,expected)

if __name__=='__main__': main()
